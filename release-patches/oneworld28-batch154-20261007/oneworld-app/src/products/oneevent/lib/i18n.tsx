type Lang = keyof typeof dict;

/**
 * ONE LANGUAGE PICKER, NOT TWO. The old app kept its own `os-lang` in localStorage — ported
 * unchanged, the header's flag (shell, `oneworld-lang`) and these screens would each speak
 * their own language, which is the "half-translated screen" bug from the other direction.
 * `useI18n` here now DERIVES from the shell's picker and only supplies the event dictionary.
 * The dict is en/es; `co` is Spanish (a bare `=== "es"` test served English to Colombia once —
 * shell i18n's own warning), and the other four fall back to English until the copy is written.
 */
export function I18nProvider({ children }: { children: React.ReactNode }) {
  return <>{children}</>;
}
export const useI18n = () => {
  const { lang: shellLang, setLang } = useShellI18n();
  const lang: Lang = (shellLang === "es" || shellLang === "co") ? "es" : "en";
  const t = (k: keyof typeof dict.en) => (dict[lang] as any)[k] ?? dict.en[k];
  return { lang, setLang, t };
};
